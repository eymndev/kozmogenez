function lerpColor(t, a, b) {
	const pa = hex(a);
	const pb = hex(b);
	return `rgb(${Math.round(lerp$1(pa[0], pb[0], t))},${Math.round(lerp$1(pa[1], pb[1], t))},${Math.round(lerp$1(pa[2], pb[2], t))})`;
}
function hex(value) {
	const n = parseInt(value.slice(1), 16);
	return [
		n >> 16 & 255,
		n >> 8 & 255,
		n & 255
	];
}
