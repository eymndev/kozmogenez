function drawHelix(ctx, cx, cy, height, reveal, p) {
	const amp = Math.min(34, height * .14);
	const steps = Math.floor(70 * reveal);
	const turns = 4.2;
	const a = [];
	const b = [];
	for (let i = 0; i <= steps; i++) {
		const t = i / 70;
		const ang = t * Math.PI * 2 * turns + p * .8;
		const y = cy - height / 2 + t * height;
		a.push({
			x: cx + Math.sin(ang) * amp,
			y,
			z: Math.cos(ang)
		});
		b.push({
			x: cx + Math.sin(ang + Math.PI) * amp,
			y,
			z: Math.cos(ang + Math.PI)
		});
	}
	for (let i = 0; i < a.length; i += 3) {
		ctx.strokeStyle = `rgba(212,160,84,${.2 + (a[i].z + 1) / 2 * .75})`;
		ctx.lineWidth = 1.6;
		ctx.beginPath();
		ctx.moveTo(a[i].x, a[i].y);
		ctx.lineTo(b[i].x, b[i].y);
		ctx.stroke();
	}
	strokeStrand(ctx, a, "#f3efe4");
	strokeStrand(ctx, b, "#f3efe4");
}
function strokeStrand(ctx, pts, color) {
	if (pts.length < 2) return;
	ctx.beginPath();
	ctx.moveTo(pts[0].x, pts[0].y);
	for (let i = 1; i < pts.length; i++) ctx.lineTo(pts[i].x, pts[i].y);
	ctx.strokeStyle = color;
	ctx.lineWidth = 2.6;
	ctx.lineJoin = "round";
	ctx.stroke();
}
